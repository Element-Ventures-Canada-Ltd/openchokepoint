"""Export an OpenChokepoint instance file as W3C PROV-O (https://www.w3.org/TR/prov-o/).

Usage:
    python3 tools/export_prov.py [--format ttl|json-ld] [instance.yaml ...]

--format ttl (default) emits Turtle; --format json-ld emits JSON-LD.
Defaults to the synthetic examples. Requires PyYAML and rdflib.

Mapping: docs/standards-crosswalk.md, sections 2 and 3. Each object becomes a
PROV entity, activity, agent or location; each link becomes the closest PROV
relation. Where PROV expresses nothing (flags, alternate_for), the link is
kept in the graph under an OCP namespace property so no information is lost.
The exporter adds no facts and infers no order: an `underwent` link without a
`sequence` is emitted as a plain prov:used triple, exactly as the instance
file states it.
"""
import argparse
import datetime
import sys
from pathlib import Path

import yaml  # noqa: F401  (kept for parity with validate.py; Registry loads it)
from rdflib import Graph, Literal, Namespace, URIRef
from rdflib.namespace import RDF, XSD

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "sdk" / "python"))
from openchokepoint.registry import Registry  # noqa: E402

PROV = Namespace("http://www.w3.org/ns/prov#")
OCP = Namespace("https://openchokepoint.example/ns#")         # fictional reserved base
OCP_RECORD = Namespace("https://openchokepoint.example/record/")  # fictional record ids

# --- object-type mapping (crosswalk section 2) ------------------------------
OBJECT_KINDS = {
    "Entity":         PROV.Agent,      # an organization that holds a capability: agent
    "Facility":       PROV.Location,   # a physical site: location (subclass of entity)
    "Capability":     PROV.Entity,
    "Programme":      PROV.Agent,      # a demand-side programme: agent-like demand owner
    "Component":      PROV.Entity,     # a part design: entity
    "SerialItem":     PROV.Entity,     # one physical piece: entity
    "MaterialLot":    PROV.Entity,     # a batch: entity
    "ProcessStep":    PROV.Activity,   # a controlled operation: activity
    "EvidenceRecord": PROV.Entity,     # a pointer to proof: entity
    "CriticalItem":   PROV.Entity,     # a judgment flag: entity
}

# --- link-type mapping (crosswalk section 3) --------------------------------
# value: (predicate, flip). flip=True means the PROV relation reads
# object -> subject (e.g. capability prov:wasAttributedTo provider).
LINK_PREDICATES = {
    "instance_of":   (PROV.specializationOf, False),   # serial is a specialization of its design
    "made_from":     (PROV.wasDerivedFrom, False),     # item derived from its material lot
    "produced_by":   (PROV.wasAttributedTo, False),    # lot attributed to the producing organization
    "located_at":    (PROV.atLocation, False),         # entity at facility
    "provides_capability": (PROV.wasAttributedTo, True),  # capability attributed to its provider
    "requires_capability": (OCP.requiresCapability, False),  # no PROV counterpart (partial)
    "supplies":      (OCP.supplies, False),            # no PROV counterpart (partial)
    "underwent":     (PROV.used, True),                # the step (activity) used the serial item
    "evidenced_by":  (PROV.wasGeneratedBy, True),      # the evidence was generated by the step
    "performed_at":  (PROV.atLocation, False),         # activity at location
    "flags":         (OCP.flags, False),               # no PROV counterpart (none)
    "alternate_for": (OCP.alternateFor, False),        # no PROV counterpart (none)
}

# schema fields that describe the record itself, not a graph fact
RESERVED = {"type", "id", "from", "to"}


def _uri(record_id):
    return OCP_RECORD[str(record_id)]


def _lit(value):
    if isinstance(value, datetime.date):
        return Literal(value.isoformat(), datatype=XSD.date)
    if isinstance(value, bool):
        return Literal(value, datatype=XSD.boolean)
    if isinstance(value, int):
        return Literal(value, datatype=XSD.integer)
    if isinstance(value, float):
        return Literal(value, datatype=XSD.double)
    return Literal(str(value))


def _add_props(g, uri, record):
    for key, value in record.data.items():
        if key in RESERVED:
            continue
        if isinstance(value, list):
            for item in value:
                g.add((uri, OCP[key], _lit(item)))
            continue
        lit = _lit(value)
        if lit is None:
            continue
        g.add((uri, OCP[key], lit))


def build_graph(registry):
    g = Graph()
    g.bind("prov", PROV)
    g.bind("ocp", OCP)
    g.bind("ocpr", OCP_RECORD)

    for obj in registry.objects:
        uri = _uri(obj.id)
        g.add((uri, RDF.type, OBJECT_KINDS.get(obj.type, PROV.Entity)))
        _add_props(g, uri, obj)

    for link in registry.links:
        from_uri, to_uri = _uri(link.get("from")), _uri(link.get("to"))
        spec = LINK_PREDICATES.get(link.type)
        if spec is not None:
            predicate, flip = spec
            subj, obj = (to_uri, from_uri) if flip else (from_uri, to_uri)
            g.add((subj, predicate, obj))
        # link-level facts: sequence (step order), maturity, item ...
        for key, value in link.data.items():
            if key in RESERVED or key == "type":
                continue
            if isinstance(value, list):
                for item in value:
                    g.add((to_uri, OCP[key], _lit(item)))
                continue
            lit = _lit(value)
            if lit is None:
                continue
            # sequence describes the step's position on the item's route
            if key == "sequence":
                g.add((to_uri, OCP.sequence, lit))
            else:
                g.add((to_uri, OCP[key], lit))
    return g


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--format", choices=("ttl", "json-ld"), default="ttl")
    parser.add_argument("instances", nargs="*", help="instance YAML files (default: examples/*.yaml)")
    args = parser.parse_args(argv)

    targets = args.instances or sorted((ROOT / "examples").glob("*.yaml"))
    failed = False
    for target in targets:
        try:
            reg = Registry.load(target)
        except Exception as exc:  # noqa: BLE001
            print(f"FAIL {target}: {exc}", file=sys.stderr)
            failed = True
            continue
        g = build_graph(reg)
        if args.format == "ttl":
            sys.stdout.write(g.serialize(format="turtle"))
        else:
            sys.stdout.write(g.serialize(format="json-ld") + "\n")
        print(f"OK   {target} ({len(g)} triples)", file=sys.stderr)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
